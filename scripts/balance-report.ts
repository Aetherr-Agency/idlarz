/**
 * Generates docs/generated/balance-tables.md from the REAL game config + utils,
 * so the documentation can be regenerated after any tuning change.
 *
 * Run (no dependency added; tsx resolves the "@/..." alias from tsconfig.json):
 *   npx tsx scripts/balance-report.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
	ANIMALS,
	BASE_GENERATION_RATES,
	BASE_XP_PER_LEVEL,
	BIOMES,
	CASTLE_BASE_RATES,
	CASTLE_UPGRADE,
	GRID_CENTER_X,
	GRID_CENTER_Y,
	GRID_HEIGHT,
	GRID_SIZE,
	INITIAL_CHARACTER_STATS,
	MERCHANT_RESOURCE_PRICES,
	SCALING_CONFIG,
	XP_GROWTH_FACTOR,
} from '../src/config/gameConfig';
import {
	calculateAnimalCost,
	calculateAnimalProduction,
	calculateCombatStats,
	calculateResourceRates,
	calculateStatResourceModifiers,
	calculateXpGain,
	countOwnedTiles,
	createInitialGrid,
	getRandomBiome,
} from '../src/utils/gameUtils';
import type { Resources, Tile } from '../src/types/game';

const out: string[] = [];
const line = (s = '') => out.push(s);

const fmt = (n: number): string => {
	if (!isFinite(n)) return '∞';
	const a = Math.abs(n);
	if (a >= 1e12) return `${(n / 1e12).toFixed(2)}T`;
	if (a >= 1e9) return `${(n / 1e9).toFixed(2)}B`;
	if (a >= 1e6) return `${(n / 1e6).toFixed(2)}M`;
	if (a >= 1e4) return `${(n / 1e3).toFixed(2)}K`;
	if (a < 100) return n.toFixed(2);
	return n.toFixed(0);
};

const duration = (s: number): string => {
	if (!isFinite(s)) return '∞';
	if (s < 90) return `${s.toFixed(0)}s`;
	if (s < 5400) return `${(s / 60).toFixed(1)}m`;
	if (s < 172800) return `${(s / 3600).toFixed(1)}h`;
	return `${(s / 86400).toFixed(1)}d`;
};

const table = (head: string[], rows: (string | number)[][]) => {
	line(`| ${head.join(' | ')} |`);
	line(`| ${head.map(() => '---').join(' | ')} |`);
	rows.forEach((r) => line(`| ${r.join(' | ')} |`));
	line();
};

const tileCost = (owned: number, charisma = INITIAL_CHARACTER_STATS.charisma) => {
	const discount = Math.min(charisma * 0.005, 0.25);
	return Math.floor(SCALING_CONFIG.costFormula(owned) * (1 - discount));
};

line('# Generated balance tables');
line();
line(
	'> Generated by `npx tsx scripts/balance-report.ts` from the real config/utils. Do not edit by hand.'
);
line();

// ---------------------------------------------------------------------------
line('## 1. Tile cost and XP per tile');
line();
line(
	'`n` = tiles owned *before* the purchase (the castle counts, so the first purchase is n = 1). ' +
		'Cost is the **undiscounted** formula and the cost with the starting Charisma (5 → 2.5% discount). ' +
		'"Pick" marks purchases where the player chooses the biome (`n % 4 === 3`). ' +
		'XP is before the XP-gain multiplier.'
);
line();
{
	const rows: (string | number)[][] = [];
	let cumulative = 0;
	for (let n = 1; n <= 80; n++) {
		const base = SCALING_CONFIG.costFormula(n);
		const cost = tileCost(n);
		cumulative += cost;
		rows.push([
			n,
			fmt(base),
			fmt(cost),
			fmt(cumulative),
			fmt(calculateXpGain(n + 1)),
			n % 4 === 3 ? 'pick' : '',
		]);
	}
	table(['n', 'base cost', 'cost (cha 5)', 'cumulative', 'XP gained', 'Pick'], rows);
}

// ---------------------------------------------------------------------------
line('## 2. Level curve');
line();
line(
	`XP needed to go from level L to L+1 = \`floor(${BASE_XP_PER_LEVEL} × ${XP_GROWTH_FACTOR}^(L-1))\`. One stat point per level gained.`
);
line();
{
	const rows: (string | number)[][] = [];
	let cumulative = 0;
	for (let L = 1; L <= 40; L++) {
		const step = Math.floor(BASE_XP_PER_LEVEL * Math.pow(XP_GROWTH_FACTOR, L - 1));
		cumulative += step;
		rows.push([L, fmt(step), fmt(cumulative), L]);
	}
	table(['Level', 'XP to next', 'cumulative XP to reach L+1', 'stat points earned so far'], rows);
}

// ---------------------------------------------------------------------------
line('## 3. Castle');
line();
line(
	`Resource modifier at level L = \`${CASTLE_UPGRADE.baseResourceMultiplier} × 2^(L-1)\` (added to **every** resource's modifier). ` +
		`Max level = ${CASTLE_UPGRADE.maxLevel}, so only the first ${CASTLE_UPGRADE.maxLevel - 1} cost entries are reachable.`
);
line();
{
	const resKeys: (keyof Resources)[] = ['gold', 'wood', 'stone', 'coal', 'food', 'meat'];
	const rows: (string | number)[][] = [];
	CASTLE_UPGRADE.upgradeCosts.forEach((c, i) => {
		const from = i + 1;
		const reachable = from < CASTLE_UPGRADE.maxLevel;
		rows.push([
			`${from} → ${from + 1}`,
			reachable ? 'yes' : '**unused**',
			`+${(CASTLE_UPGRADE.baseResourceMultiplier * Math.pow(2, from) * 100).toFixed(0)}%`,
			...resKeys.map((k) => ((c as Partial<Resources>)[k] ? fmt((c as Partial<Resources>)[k] as number) : '—')),
		]);
	});
	table(
		['Upgrade', 'Reachable', 'Modifier after', ...resKeys.map((k) => k)],
		rows
	);
	line(
		`Modifier at level 1 = +${(CASTLE_UPGRADE.baseResourceMultiplier * 100).toFixed(0)}%; ` +
			`at max level ${CASTLE_UPGRADE.maxLevel} = +${(CASTLE_UPGRADE.baseResourceMultiplier * Math.pow(2, CASTLE_UPGRADE.maxLevel - 1) * 100).toFixed(0)}%.`
	);
	line();
}

// ---------------------------------------------------------------------------
line('## 4. Farm animals');
line();
line(
	'Level N is the N-th purchase of that animal. Cost (food) of reaching level N = `floor(baseCost × costScaling^(N-1))`; ' +
		'production of the animal at level N = `baseProduction × productionScaling^(N-1)` meat/s (before the Plains/castle/stat meat modifiers). ' +
		`Payback = food cost × ${MERCHANT_RESOURCE_PRICES.food} gold (what the food would sell for) ÷ (marginal meat/s × ${MERCHANT_RESOURCE_PRICES.meat} gold sell price).`
);
line();
ANIMALS.forEach((a) => {
	line(`### ${a.name} (cost ${fmt(a.baseCost)} × ${a.costScaling}ⁿ, production ${a.baseProduction} × ${a.productionScaling}ⁿ)`);
	line();
	const rows: (string | number)[][] = [];
	let cumFood = 0;
	for (let N = 1; N <= 20; N++) {
		const cost = calculateAnimalCost(a, N - 1);
		cumFood += cost;
		const prod = calculateAnimalProduction(a, N);
		const marginal = prod - calculateAnimalProduction(a, N - 1);
		const paybackS = (cost * MERCHANT_RESOURCE_PRICES.food) / (marginal * MERCHANT_RESOURCE_PRICES.meat);
		rows.push([N, fmt(cost), fmt(cumFood), fmt(prod), fmt(marginal), duration(paybackS)]);
	}
	table(['Level', 'cost (food)', 'cumulative food', 'meat/s at level', 'marginal meat/s', 'payback'], rows);
});

// ---------------------------------------------------------------------------
line('## 5. Biome resource tables');
line();
{
	const rows = Object.values(BIOMES).map((b) => [
		b.label,
		b.unique ? 'unique' : '',
		b.upgradeable ? 'upgradeable' : '',
		Object.entries(b.resourceGeneration)
			.map(([k, v]) => `${k} ${v}`)
			.join(', ') || '—',
	]);
	table(['Biome', 'Unique', 'Upgradeable', 'Base per-second generation'], rows);
}

// ---------------------------------------------------------------------------
line('## 6. Stat → resource modifier per point (additive, fraction)');
line();
{
	const zero = { strength: 0, dexterity: 0, intelligence: 0, vitality: 0, charisma: 0 };
	const rows: (string | number)[][] = [];
	(Object.keys(zero) as (keyof typeof zero)[]).forEach((k) => {
		const m = calculateStatResourceModifiers({
			...INITIAL_CHARACTER_STATS,
			...zero,
			[k]: 1,
		});
		const parts = Object.entries(m)
			.filter(([, v]) => v > 0)
			.map(([r, v]) => `${r} +${(v * 100).toFixed(2)}%`);
		rows.push([k, parts.join(', ')]);
	});
	table(['Stat (1 point)', 'Resource modifiers'], rows);

	const c = calculateCombatStats(INITIAL_CHARACTER_STATS as never);
	line('Derived combat stats, starting stats (all 5):');
	line();
	table(
		['Stat', 'calculateCombatStats()', 'INITIAL_CHARACTER_STATS'],
		Object.entries(c).map(([k, v]) => [
			k,
			String(v),
			String(INITIAL_CHARACTER_STATS[k as keyof typeof INITIAL_CHARACTER_STATS]),
		])
	);
}

// ---------------------------------------------------------------------------
line('## 7. Rates of a brand-new game');
line();
{
	const grid = createInitialGrid();
	const r = calculateResourceRates(grid, INITIAL_CHARACTER_STATS, {});
	const keys = Object.keys(r.total) as (keyof Resources)[];
	table(
		['Resource', 'BASE_GENERATION_RATES', 'CASTLE_BASE_RATES', 'base (computed)', 'modifier (computed)', 'total /s'],
		keys.map((k) => [
			k,
			BASE_GENERATION_RATES[k],
			CASTLE_BASE_RATES[k],
			r.base[k].toFixed(3),
			`${(r.modifiers[k] * 100).toFixed(1)}%`,
			r.total[k].toFixed(3),
		])
	);
	line(
		'Note: `modifiers` is initialised from `BASE_GENERATION_RATES` in `calculateResourceRates`, ' +
			'so gold and xp start with +10% / +25% before the castle and stat modifiers (see docs/04, issue D1).'
	);
	line();
}

// ---------------------------------------------------------------------------
line('## 8. Time to afford the next tile at a constant gold income');
line();
{
	const incomes = [1, 5, 25, 100, 500, 2500, 10000];
	const rows: (string | number)[][] = [];
	for (let n = 1; n <= 80; n += n < 10 ? 1 : 5) {
		rows.push([n, fmt(tileCost(n)), ...incomes.map((i) => duration(tileCost(n) / i))]);
	}
	table(['n', 'cost', ...incomes.map((i) => `${i}/s`)], rows);
}

// ---------------------------------------------------------------------------
line('## 9. Idle-only baseline simulation');
line();
line(
	'Pure idle play: buy the nearest affordable tile as soon as gold allows (random biome every time, ' +
		'no manual biome picks, no castle upgrades, no stat points, no clicking, no chests, no merchant/farm). ' +
		'Seeded RNG, so it is reproducible. Income uses the real `calculateResourceRates` with starting stats.'
);
line();
{
	let seed = 12345;
	const origRandom = Math.random;
	Math.random = () => {
		seed = (seed + 0x6d2b79f5) | 0;
		let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
		t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};

	const grid: Tile[][] = createInitialGrid();
	let gold = 125;
	let time = 0;
	const rows: (string | number)[][] = [];
	const rates = () => calculateResourceRates(grid, INITIAL_CHARACTER_STATS, {});
	const frontier = () => {
		let best: [number, number] | null = null;
		let bestD = Infinity;
		for (let y = 0; y < GRID_HEIGHT; y++) {
			for (let x = 0; x < GRID_SIZE; x++) {
				if (grid[y][x].isOwned) continue;
				const adj = [
					[x - 1, y],
					[x + 1, y],
					[x, y - 1],
					[x, y + 1],
				].some(([ax, ay]) => grid[ay]?.[ax]?.isOwned);
				if (!adj) continue;
				const d = Math.abs(x - GRID_CENTER_X) + Math.abs(y - GRID_CENTER_Y);
				if (d < bestD) {
					bestD = d;
					best = [x, y];
				}
			}
		}
		return best!;
	};

	for (let step = 0; step < 70; step++) {
		const owned = countOwnedTiles(grid);
		const cost = tileCost(owned);
		const r = rates().total.gold;
		if (gold < cost) {
			time += (cost - gold) / r;
			gold = cost;
		}
		gold -= cost;
		const [x, y] = frontier();
		grid[y][x] = { biome: getRandomBiome(), isOwned: true };
		const ownedAfter = owned + 1;
		const after = rates();
		if (ownedAfter % 5 === 0 || ownedAfter <= 6) {
			rows.push([ownedAfter, fmt(cost), duration(time), after.total.gold.toFixed(2), after.total.xp.toFixed(2)]);
		}
	}
	Math.random = origRandom;
	table(['Tiles owned', 'last tile cost', 'elapsed (idle only)', 'gold/s after', 'xp/s after'], rows);
}

// ---------------------------------------------------------------------------
line('## 10. Candidate tile-cost curves (proposals, not applied)');
line();
line(
	'Base cost (no charisma discount) for n tiles owned. A = current game. B = same start, gentler tail (x1.22 per tile after 20). ' +
		'C = flat x1.30. D = flat x1.25. Compare the cumulative columns with the income you expect at that stage.'
);
line();
{
	const curves: Record<string, (n: number) => number> = {
		A: (n) => SCALING_CONFIG.costFormula(n),
		B: (n) => Math.floor(55 * Math.pow(1.42, Math.min(n, 20)) * Math.pow(1.22, Math.max(n - 20, 0))),
		C: (n) => Math.floor(55 * Math.pow(1.3, n)),
		D: (n) => Math.floor(55 * Math.pow(1.25, n)),
	};
	const ns = [10, 15, 20, 25, 30, 35, 40, 50, 60];
	table(['n', ...Object.keys(curves)], ns.map((n) => [n, ...Object.values(curves).map((f) => fmt(f(n)))]));
	const cum = (f: (n: number) => number, upTo: number) => {
		let t = 0;
		for (let n = 1; n <= upTo; n++) t += f(n);
		return t;
	};
	table(
		['cumulative cost to own', ...Object.keys(curves)],
		[20, 30, 40, 50].map((k) => [`${k} tiles`, ...Object.values(curves).map((f) => fmt(cum(f, k - 1)))])
	);
}

const target = resolve(dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../docs/generated/balance-tables.md');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target} (${out.length} lines)`);
